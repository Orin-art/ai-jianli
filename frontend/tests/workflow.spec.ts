test('全部重复的导入批次可从预览和历史中取消', async ({ page }) => {
  const fixture = resolve('tests/fixtures/cancel.xlsx')
  const title = `取消导入-${Date.now()}`
  execFileSync(resolve('../.venv/Scripts/python.exe'), ['-c', `import sys; from pathlib import Path; sys.path.insert(0,str(Path('../backend').resolve())); from app.imports import HEADERS; from openpyxl import Workbook; p=Path(${JSON.stringify(fixture)}); p.parent.mkdir(parents=True,exist_ok=True); w=Workbook(); s=w.active; s.append(list(HEADERS)); s.append(['${title}','测试企业','上海']); w.save(p)`])
  const headers = { 'X-Requested-With': 'career-web' }
  const login = await page.request.post('/api/auth/login', { headers, data: { username: 'e2e-admin', password: 'E2e-Only-Password-123' } })
  expect(login.ok()).toBeTruthy()
  const file = await import('node:fs/promises').then(fs => fs.readFile(fixture))
  const preview = async () => {
    const response = await page.request.post('/api/imports/preview', { headers, multipart: { file: { name: 'cancel.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: file } } })
    expect(response.ok()).toBeTruthy()
    return response.json()
  }
  const original = await preview()
  expect((await page.request.post(`/api/imports/${original.id}/commit`, { headers })).ok()).toBeTruthy()
  const duplicate = await preview()
  expect(duplicate.counts['可导入']).toBe(0)
  await page.goto('/')
  await page.getByRole('button', { name: 'Excel 导入', exact: true }).click()
  await page.getByRole('row').filter({ hasText: `#${duplicate.id}` }).getByRole('button', { name: '查看结果' }).click()
  const panel = page.locator('.batch-preview')
  await expect(panel.getByRole('button', { name: '确认入库 0 条岗位' })).toBeDisabled()
  await panel.getByRole('button', { name: '取消导入', exact: true }).click()
  await expect(panel.locator('.panel-heading .el-tag')).toHaveText('已取消')
  await expect(panel.getByText('本批次已取消，未写入岗位。校验记录保留，如需导入请重新上传。')).toBeVisible()
  await expect(panel.getByRole('button', { name: '取消导入' })).toHaveCount(0)
  expect((await page.request.post(`/api/imports/${duplicate.id}/commit`, { headers })).status()).toBe(409)
  const historyBatch = await preview()
  await page.getByRole('button', { name: '刷新数据' }).click()
  const row = page.getByRole('row').filter({ hasText: `#${historyBatch.id}` })
  await row.getByRole('button', { name: '取消导入', exact: true }).click()
  await expect(row).toContainText('已取消')
  await expect(row.getByRole('button', { name: '取消导入' })).toHaveCount(0)
  await page.screenshot({ path: '../artifacts/import-canceled.png', fullPage: true })
})


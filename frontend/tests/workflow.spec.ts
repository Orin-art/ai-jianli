test('简历删除需确认，删除后不能下载或识别且保留学员资料', async ({ page }) => {
  const unique = Date.now().toString(), name = `删除测试学员-${unique}`
  const fixture = resolve('tests/fixtures/delete-resume.docx')
  execFileSync(resolve('../.venv/Scripts/python.exe'), ['-c', `from pathlib import Path; from zipfile import ZipFile; p=Path(${JSON.stringify(fixture)}); p.parent.mkdir(parents=True,exist_ok=True); z=ZipFile(p,'w'); z.writestr('word/document.xml','<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>电话：13800138000</w:t></w:r></w:p></w:body></w:document>'); z.close()`])
  const headers = { 'X-Requested-With': 'career-web' }
  expect((await page.request.post('/api/auth/login', { headers, data: { username: 'e2e-admin', password: 'E2e-Only-Password-123' } })).ok()).toBeTruthy()
  const created = await page.request.post('/api/students', { headers, data: { name, phone: '13900139000', school: '远山大学' } })
  expect(created.ok()).toBeTruthy()
  const sid = (await created.json()).id
  const buffer = await import('node:fs/promises').then(fs => fs.readFile(fixture))
  const upload = async (filename: string) => {
    const result = await page.request.post(`/api/students/${sid}/resumes`, { headers, multipart: { file: { name: filename, mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer } } })
    expect(result.ok()).toBeTruthy()
    return (await result.json()).id
  }
  const rid = await upload('待删除简历.docx')
  await upload('保留版本.docx')
  await page.goto('/')
  await page.getByRole('button', { name: '学员与跟进', exact: true }).click()
  await page.getByRole('button', { name, exact: true }).click()
  const detail = page.locator('.student-detail')
  const row = detail.locator('.file-row').filter({ hasText: '待删除简历.docx' })
  await row.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('button', { name: '保留简历', exact: true }).click()
  await expect(row).toBeVisible()
  expect((await page.request.get(`/api/resumes/${rid}/download`)).status()).toBe(200)
  await row.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(detail.getByText('保留版本.docx', { exact: true })).toBeVisible()
  await expect(row).toHaveCount(0)
  await expect(detail.locator('.info-grid').getByText('远山大学', { exact: true })).toBeVisible()
  expect((await page.request.get(`/api/resumes/${rid}/download`)).status()).toBe(404)
  expect((await page.request.get(`/api/resumes/${rid}/extraction`)).status()).toBe(404)
  const profile = await (await page.request.get(`/api/students/${sid}`)).json()
  expect(profile.phone).toBe('13900139000'); expect(profile.resumes.length).toBe(1)
  await detail.locator('.file-row').getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(detail.getByText('尚未上传简历', { exact: true })).toBeVisible()
  await page.screenshot({ path: '../artifacts/resume-delete.png', fullPage: true })
})

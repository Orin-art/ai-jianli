import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { resolve } from 'node:path'

test('学员严格匹配：最多5个候选、逐条推荐、补位与窄屏', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('账号', { exact: true }).fill('e2e-admin')
  await page.getByLabel('密码', { exact: true }).fill('E2e-Only-Password-123')
  await page.getByRole('button', { name: '进入工作台' }).click()
  await expect(page.getByRole('heading', { name: '工作概览', exact: true })).toBeVisible()
  const unique = Date.now().toString(), city = `匹配测试城${unique}`
  const headers = { 'X-Requested-With': 'career-web' }
  const file = testInfo.outputPath('matching.xlsx')
  execFileSync(resolve('../.venv/Scripts/python.exe'), ['-c', `from openpyxl import Workbook; from app.imports import HEADERS; w=Workbook(); s=w.active; s.append(list(HEADERS)); [s.append(['后端开发-${unique}-'+str(i),'匹配测试公司','${city}','大专','1-3年','计算机',8000,12000,'参与后端研发','内部测试']) for i in range(12)]; s.append(['后端开发-硕士-${unique}','匹配测试公司','${city}','硕士','不限','计算机']); s.append(['后端开发-其他城市-${unique}','匹配测试公司','北京','大专','不限','计算机']); s.append(['前端开发-${unique}','匹配测试公司','${city}','大专','不限','计算机']); s.append(['后端开发-专业不符-${unique}','匹配测试公司','${city}','大专','不限','金融']); s.append(['后端开发-专业缺失-${unique}','匹配测试公司','${city}','大专']); w.save(${JSON.stringify(file)})`], { env: { ...process.env, PYTHONPATH: resolve('../backend') } })
  const { readFileSync } = await import('node:fs')
  const batchResponse = await page.request.post('/api/imports/preview', { headers, multipart: { file: { name: 'matching.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: readFileSync(file) } } })
  expect(batchResponse.ok()).toBeTruthy()
  const batch = await batchResponse.json()
  expect((await page.request.post(`/api/imports/${batch.id}/commit`, { headers })).ok()).toBeTruthy()
  const studentResponse = await page.request.post('/api/students', { headers, data: { name: `匹配学员${unique}`, education: '本科', major: '计算机科学', target_city: city, target_role: '后端开发' } })
  expect(studentResponse.ok()).toBeTruthy()
  const student = await studentResponse.json()
  await page.getByRole('button', { name: '学员与跟进', exact: true }).click()
  await page.getByRole('button', { name: student.name, exact: true }).click()
  const section = page.getByRole('region', { name: '学员匹配岗位' })
  await expect(section.getByRole('heading', { name: '匹配岗位 本次 5 个候选 · 最多 5 个' })).toBeVisible()
  await expect(section).toContainText('共有 12 个岗位通过规则筛选')
  await expect(section.locator('.match-card')).toHaveCount(5)
  await expect(section).toContainText('学历满足要求')
  await expect(section).toContainText('专业文本有重合')
  await expect(section).toContainText('学员经验需核对')
  await expect(section.getByRole('button', { name: '下一页', exact: true })).toHaveCount(0)
  const before = await (await page.request.get(`/api/students/${student.id}`)).json()
  expect(before.recommendations).toHaveLength(0)
  const title = await section.locator('.match-card strong').first().innerText()
  await section.getByRole('button', { name: '查看并推荐' }).first().click()
  const dialog = page.getByRole('dialog', { name: '核对匹配岗位', exact: true })
  await expect(dialog).toContainText('参与后端研发')
  await expect(dialog).toContainText(student.name)
  await dialog.getByRole('button', { name: `确认推荐给${student.name}`, exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(section).toContainText('共有 11 个岗位通过规则筛选')
  await expect(section.locator('.match-card')).toHaveCount(5)
  await expect(section.locator('.match-card').filter({ hasText: title })).toHaveCount(0)
  const stored = await (await page.request.get(`/api/students/${student.id}`)).json()
  expect(stored.recommendations[0].snapshot.title).toBe(title)
  expect(stored.recommendations).toHaveLength(1)
  const recommendationCard = page.locator('.student-detail > .recommend-card').filter({ hasText: title })
  await recommendationCard.getByRole('button', { name: '取消推荐', exact: true }).click()
  const cancelDialog = page.getByRole('dialog', { name: '取消岗位推荐', exact: true })
  await expect(cancelDialog).toContainText(title)
  await cancelDialog.getByRole('button', { name: '保留推荐', exact: true }).click()
  await expect(recommendationCard).toBeVisible()
  await recommendationCard.getByRole('button', { name: '取消推荐', exact: true }).click()
  await cancelDialog.getByRole('button', { name: '确认取消推荐', exact: true }).click()
  await expect(recommendationCard).toHaveCount(0)
  await expect(section).toContainText('共有 12 个岗位通过规则筛选')
  const returnedCard = section.locator('.match-card').filter({ hasText: title })
  await expect(returnedCard).toBeVisible()
  const afterCancel = await (await page.request.get(`/api/students/${student.id}`)).json()
  expect(afterCancel.recommendations).toHaveLength(0)
  await returnedCard.getByRole('button', { name: '查看并推荐' }).click()
  await dialog.getByRole('button', { name: `确认推荐给${student.name}`, exact: true }).click()
  await expect(recommendationCard).toBeVisible()
  await page.route(`**/api/students/${student.id}/matched-jobs`, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: '匹配暂时不可用，请重试' }) }), { times: 1 })
  await section.getByRole('button', { name: '刷新匹配' }).click()
  await expect(section.getByRole('alert')).toContainText('匹配暂时不可用，请重试')
  await section.getByRole('button', { name: '刷新匹配' }).click()
  await expect(section.locator('.match-card')).toHaveCount(5)
  await expect(page.locator('.el-loading-mask')).toHaveCount(0)
  await expect(page.locator('.el-message')).toHaveCount(0)
  await page.screenshot({ path: '../artifacts/matched-jobs.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await section.scrollIntoViewIfNeeded()
  await expect(section.getByRole('button', { name: '查看并推荐' }).first()).toBeVisible()
  const overflow = await section.evaluate(el => el.scrollWidth > el.clientWidth + 1)
  expect(overflow).toBeFalsy()
  await page.screenshot({ path: '../artifacts/matched-jobs-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
